package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"text/template"
)

// GenerateApplicationPackage 生成 application 包
func (g *DatabaseGenerator) GenerateApplicationPackage(modulePath string, modelNames []string) error {
	outputDir := filepath.Join(g.config.Output, "internal/application")
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("创建 application 目录失败: %w", err)
	}

	outputPath := filepath.Join(outputDir, "application.go")

	// 已存在则跳过
	if _, err := os.Stat(outputPath); err == nil {
		return nil
	}

	fmt.Println("📦 正在生成 internal/application/application.go...")

	tmpl := `// Code generated by go-start. DO NOT EDIT.
package application

import (
	"context"
	"fmt"
	"log"
	"os"
	"strconv"
	"time"

	"gorm.io/driver/mysql"
	"gorm.io/gorm"
	"gorm.io/gorm/logger"
	"{{.ModulePath}}/internal/controller"
	"{{.ModulePath}}/internal/repository"
	"{{.ModulePath}}/internal/routes"
	"{{.ModulePath}}/internal/service"
)

var (
	DB *gorm.DB
{{range .ModelInfos}}
	{{.LowerCamelCase}}Repo    *repository.{{.Name}}Repository
	{{.LowerCamelCase}}Service *service.{{.Name}}Service
{{end}}
)

func Init(ctx context.Context) error {
	if err := initDatabase(ctx); err != nil {
		return fmt.Errorf("初始化数据库失败: %w", err)
	}
	log.Println("✅ 数据库初始化成功")
	initRepositories()
	log.Println("✅ Repository 层初始化成功")
	initServices()
	log.Println("✅ Service 层初始化成功")
	return nil
}

func initDatabase(ctx context.Context) error {
	dsn := getEnv("DATABASE_DSN", "root:password@tcp(localhost:3306)/mydb?charset=utf8mb4&parseTime=True&loc=Local")

	var logLevel logger.LogLevel
	switch getEnv("LOG_LEVEL", "info") {
	case "silent":
		logLevel = logger.Silent
	case "error":
		logLevel = logger.Error
	case "warn":
		logLevel = logger.Warn
	default:
		logLevel = logger.Info
	}

	db, err := gorm.Open(mysql.Open(dsn), &gorm.Config{
		Logger: logger.Default.LogMode(logLevel),
	})
	if err != nil {
		return err
	}

	sqlDB, _ := db.DB()
	sqlDB.SetMaxIdleConns(getIntEnv("DB_MAX_IDLE_CONNS", 10))
	sqlDB.SetMaxOpenConns(getIntEnv("DB_MAX_OPEN_CONNS", 100))
	sqlDB.SetConnMaxLifetime(time.Duration(getIntEnv("DB_CONN_MAX_LIFETIME", 3600)) * time.Second)

	DB = db
	return nil
}

func initRepositories() {
{{range .ModelInfos}}
	{{.LowerCamelCase}}Repo = repository.New{{.Name}}Repository(DB)
{{end}}
}

func initServices() {
{{range .ModelInfos}}
	{{.LowerCamelCase}}Service = service.New{{.Name}}Service({{.LowerCamelCase}}Repo)
{{end}}
}

func GetControllers() []interface{} {
	return []interface{}{
{{range .ModelInfos}}
		controller.New{{.Name}}Controller({{.LowerCamelCase}}Service),
{{end}}
	}
}

func RegisterRoutes(r interface{ Group(string, ...interface{}) interface{} }) {
{{range .ModelInfos}}
	routes.Register{{.Name}}Routes(r.(interface{ Group(string, ...interface{}) interface{} }), controller.New{{.Name}}Controller({{.LowerCamelCase}}Service))
{{end}}
}

func getEnv(key, defaultVal string) string {
	if val := os.Getenv(key); val != "" {
		return val
	}
	return defaultVal
}

func getIntEnv(key string, defaultVal int) int {
	if val := os.Getenv(key); val != "" {
		if n, err := strconv.Atoi(val); err == nil {
			return n
		}
	}
	return defaultVal
}
`

	type ModelInfo struct {
		Name          string
		LowerCamelCase string
	}

	type Data struct {
		ModulePath string
		ModelInfos []ModelInfo
	}

	var infos []ModelInfo
	for _, name := range modelNames {
		infos = append(infos, ModelInfo{
			Name:           name,
			LowerCamelCase: toLowerCamelCase(name),
		})
	}

	data := Data{
		ModulePath: modulePath,
		ModelInfos: infos,
	}

	t, err := template.New("application").Parse(tmpl)
	if err != nil {
		return fmt.Errorf("解析模板失败: %w", err)
	}

	f, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("创建文件失败: %w", err)
	}
	defer f.Close()

	if err := t.Execute(f, data); err != nil {
		return fmt.Errorf("渲染模板失败: %w", err)
	}

	fmt.Println("   ✓ application.go 生成成功")
	return nil
}
